import { FoodItem, ServingUnit } from '../types';

/**
 * Standard reference gram equivalents for household Bangladeshi serving units:
 * - grams: 1g
 * - tbsp (টেবিল চামচ): 15g
 * - katori (ছোট বাটি / ডালের বাটি): 100g
 * - cup (মেজারিং কাপ / মাঝারি বাটি): 150g
 * - plate (ভাতের প্লেট): 250g
 * - glass (পানির/দুধের গ্লাস): 250g (250ml)
 * - piece (টি / টুকরো): uses food.gramsPerUnit if defaultUnit === 'piece', else 60g
 */
export function getUnitGramWeight(unit: string, food?: FoodItem | null): number {
  switch (unit) {
    case 'grams':
      return 1;
    case 'tbsp':
      return 15;
    case 'katori':
      return 100;
    case 'cup':
      return 150;
    case 'plate':
      return 250;
    case 'glass':
      return 250;
    case 'piece':
      if (food && food.defaultUnit === 'piece' && food.gramsPerUnit > 0) {
        return food.gramsPerUnit;
      }
      return food?.gramsPerUnit || 60;
    default:
      return 100;
  }
}

/**
 * Calculates total grams and scaled macronutrients for any food item, portion, and unit.
 */
export function calculateFoodNutrition(
  food: FoodItem,
  portion: number,
  unit: ServingUnit | string
): {
  totalGrams: number;
  calories: number;
  protein: number;
  carbs: number;
  fat: number;
  fiber: number;
} {
  const safePortion = Math.max(0, Number(portion) || 0);

  // Base reference weight in grams for the food's stored nutrition values
  const baseGrams =
    food.defaultUnit === 'grams'
      ? 100
      : food.gramsPerUnit > 0
      ? food.gramsPerUnit
      : getUnitGramWeight(food.defaultUnit, food);

  // Selected unit weight in grams
  const selectedUnitGrams =
    unit === food.defaultUnit && unit !== 'grams'
      ? baseGrams
      : getUnitGramWeight(unit, food);

  const totalGrams = Math.round(safePortion * selectedUnitGrams);
  const scaleFactor = baseGrams > 0 ? (safePortion * selectedUnitGrams) / baseGrams : safePortion;

  return {
    totalGrams,
    calories: Math.round(food.caloriesPer100gOrUnit * scaleFactor),
    protein: Number((food.proteinPer100gOrUnit * scaleFactor).toFixed(1)),
    carbs: Number((food.carbsPer100gOrUnit * scaleFactor).toFixed(1)),
    fat: Number((food.fatPer100gOrUnit * scaleFactor).toFixed(1)),
    fiber: Number(((food.fiberPer100gOrUnit || 0) * scaleFactor).toFixed(1)),
  };
}

